"""Split the 103 labelled screenshots into train/val, class-aware.

A plain random split is unsafe at this size: rank_number, text_input and logo
each live in only 3 images, so chance alone can put every instance on one side
and leave the val metric for that class undefined. Rarest class first, seed one
image onto each side, then fill the rest randomly.

    python scripts/split_dataset.py
    python scripts/split_dataset.py --val 20 --seed 42
    python scripts/split_dataset.py --kfold 5
"""
from collections import Counter, defaultdict
from pathlib import Path
import argparse
import random
import shutil
import sys

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "data" / "renamed" / "images"
LABELS = ROOT / "data" / "labels_16"
DS = ROOT / "ds"
CONFIG = ROOT / "config"

CLASSES_16 = (CONFIG / "classes_16.txt").read_text().split()


def load():
    """stem -> Counter of class names present, plus the image path."""
    per_img, paths = {}, {}
    for label in sorted(LABELS.glob("*.txt")):
        matches = list(IMAGES.glob(f"{label.stem}.*"))
        if not matches:
            sys.exit(f"no image for {label.stem} in {IMAGES}")
        paths[label.stem] = matches[0]
        per_img[label.stem] = Counter(
            CLASSES_16[int(line.split()[0])]
            for line in label.read_text().splitlines() if line.strip())
    return per_img, paths


def carriers(per_img):
    """class name -> sorted list of stems containing it."""
    out = defaultdict(list)
    for stem in sorted(per_img):
        for name in per_img[stem]:
            out[name].append(stem)
    return out


def split(per_img, val_size, seed):
    """Seed each class onto both sides rarest-first, then fill val at random."""
    rng = random.Random(seed)
    by_class = carriers(per_img)
    val, train = set(), set()

    # rarest first: these have the fewest images to choose from, so they pick
    # before the common classes have used those images up
    for name in sorted(CLASSES_16, key=lambda n: len(by_class[n])):
        for side in (val, train):
            others = train if side is val else val
            if any(s in side for s in by_class[name]):
                continue                  # already covered on this side
            free = [s for s in by_class[name] if s not in side and s not in others]
            if not free:
                continue                  # impossible - reported as a warning below
            if side is val and len(val) >= val_size:
                continue                  # would overshoot the val budget
            side.add(rng.choice(free))

    rest = [s for s in sorted(per_img) if s not in val and s not in train]
    rng.shuffle(rest)
    need = max(0, val_size - len(val))
    val.update(rest[:need])
    train.update(rest[need:])
    return sorted(train), sorted(val)


def report(per_img, train, val, label_a="train", label_b="val", folds=None):
    """Side-by-side per-class instance counts. Returns classes missing from val."""
    a = sum((per_img[s] for s in train), Counter())
    b = sum((per_img[s] for s in val), Counter())
    by_class = carriers(per_img)

    print(f"\n{'':<18}{label_a:>8}{label_b:>8}{'':>4}{'imgs':>6}")
    print("-" * 46)
    for name in CLASSES_16:
        flag = "  <-- ABSENT" if not b[name] else ""
        print(f"{name:<18}{a[name]:>8}{b[name]:>8}{'':>4}{len(by_class[name]):>6}{flag}")
    print("-" * 46)
    print(f"{'TOTAL':<18}{sum(a.values()):>8}{sum(b.values()):>8}")
    print(f"{'images':<18}{len(train):>8}{len(val):>8}")

    missing = [n for n in CLASSES_16 if not b[n]]
    for name in missing:
        n_imgs = len(by_class[name])
        if n_imgs < 2:
            why = "only 1 image carries it, so it cannot be on both sides at once"
        elif folds and n_imgs < folds:
            # unavoidable arithmetic, not a bug: too few carriers to reach every fold
            why = (f"only {n_imgs} images carry it across {folds} folds, so at "
                   f"least {folds - n_imgs} fold(s) must miss it")
        else:
            why = f"all {n_imgs} images carrying it landed in {label_a} for this split"
        bang = "!" * 62
        print(f"\n{bang}\nWARNING: '{name}' has no instances in {label_b} - {why}.\n"
              f"Any {label_b} metric for '{name}' will be undefined. Do not read\n"
              f"it as a model failure.\n{bang}")
    return missing


def write_yaml(path, root, train, val, note):
    """Ultralytics data yaml. train/val may be a dir name or a .txt path list."""
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(CLASSES_16))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# {note}\n"
        f"# Generated by scripts/split_dataset.py - do not hand-edit.\n"
        f"path: {root.as_posix()}\n"
        f"train: {train}\n"
        f"val: {val}\n"
        f"nc: {len(CLASSES_16)}\n"
        f"names:\n{names}\n")
    return path


def copy_split(paths, train, val):
    for side, stems in (("train", train), ("val", val)):
        for kind in ("images", "labels"):
            d = DS / kind / side
            if d.exists():
                shutil.rmtree(d)       # stale members would silently poison a run
            d.mkdir(parents=True)
        for stem in stems:
            shutil.copy2(paths[stem], DS / "images" / side / paths[stem].name)
            shutil.copy2(LABELS / f"{stem}.txt", DS / "labels" / side / f"{stem}.txt")


def do_split(args, per_img, paths):
    train, val = split(per_img, args.val, args.seed)
    copy_split(paths, train, val)
    missing = report(per_img, train, val)
    yaml = write_yaml(CONFIG / "ui.yaml", DS, "images/train", "images/val",
                      f"split: {len(train)} train / {len(val)} val, seed {args.seed}")
    print(f"\nWrote {DS}/images/(train,val) and {DS}/labels/(train,val)")
    print(f"Wrote {yaml}")
    return missing


def do_kfold(args, per_img, paths):
    """N folds sharing one copy of the data; each fold is a pair of path lists.

    Copying the dataset N times would duplicate client screenshots N times on
    disk for no benefit, so the images land once in ds/images/all and each fold
    is a .txt list of paths. Ultralytics finds labels by swapping /images/ for
    /labels/ in each path, which is why 'all' exists under both.
    """
    n = args.kfold
    for kind in ("images", "labels"):
        d = DS / kind / "all"
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)
    for stem, src in paths.items():
        shutil.copy2(src, DS / "images" / "all" / src.name)
        shutil.copy2(LABELS / f"{stem}.txt", DS / "labels" / "all" / f"{stem}.txt")

    # deal the images carrying the rarest classes out first, so every fold gets
    # a share of them instead of one fold hoarding all 3 rank_number images
    by_class = carriers(per_img)
    rarity = {s: (min(len(by_class[c]) for c in per_img[s]) if per_img[s] else 10**6)
              for s in per_img}
    stems = sorted(per_img, key=lambda s: (rarity[s], s))
    rng = random.Random(args.seed)
    folds = [[] for _ in range(n)]
    for i, stem in enumerate(stems):
        folds[i % n].append(stem)
    for fold in folds:
        rng.shuffle(fold)

    lists = DS / "folds"
    lists.mkdir(parents=True, exist_ok=True)
    any_missing = False
    for i in range(n):
        val = sorted(folds[i])
        train = sorted(s for j, f in enumerate(folds) if j != i for s in f)
        for side, members in (("train", train), ("val", val)):
            (lists / f"fold{i}_{side}.txt").write_text("\n".join(
                (DS / "images" / "all" / paths[s].name).as_posix()
                for s in members) + "\n")
        print(f"\n{'=' * 46}\nFOLD {i}\n{'=' * 46}")
        any_missing |= bool(report(per_img, train, val, "train", f"val{i}", folds=n))
        write_yaml(CONFIG / "folds" / f"ui_fold{i}.yaml", DS,
                   f"folds/fold{i}_train.txt", f"folds/fold{i}_val.txt",
                   f"fold {i} of {n}, seed {args.seed}")
    print(f"\nWrote {n} fold configs to {CONFIG / 'folds'}")
    print(f"Wrote path lists to {lists} (images copied once to {DS}/images/all)")
    return any_missing


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--val", type=int, default=20, help="val images (default 20)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--kfold", type=int, help="write N fold configs instead")
    args = ap.parse_args()

    per_img, paths = load()
    print(f"labelled images: {len(per_img)}")
    if args.kfold:
        if not 2 <= args.kfold <= len(per_img):
            sys.exit(f"--kfold must be 2..{len(per_img)}")
        do_kfold(args, per_img, paths)
    else:
        if not 0 < args.val < len(per_img):
            sys.exit(f"--val must be 1..{len(per_img) - 1}")
        do_split(args, per_img, paths)


if __name__ == "__main__":
    main()
